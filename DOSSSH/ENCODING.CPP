static unsigned OemCp437ToUnicode(unsigned char c)
{
	if( c < 0x80 )
		return c;
	return g_cp437_to_unicode[c - 0x80];
}

static unsigned OemCp850ToUnicode(unsigned char c)
{
	if( c < 0x80 )
		return c;
	return g_cp850_to_unicode[c - 0x80];
}

static unsigned OemCp852ToUnicode(unsigned char c)
{
	if( c < 0x80 )
		return c;
	return g_cp852_to_unicode[c - 0x80];
}

static unsigned OemCp866ToUnicode(unsigned char c)
{
	if( c < 0x80 )
		return c;
	return g_cp866_to_unicode[c - 0x80];
}

static unsigned DosOemUnicode(unsigned char ch)
{
	switch( g_dosCodePage )
	{
	case 850: return OemCp850ToUnicode(ch);
	case 852: return OemCp852ToUnicode(ch);
	case 866: return OemCp866ToUnicode(ch);
	default:  return OemCp437ToUnicode(ch);
	}
}

unsigned char DosUnicodeOem(unsigned long ch)
{
	if( ch < 128ul )
		return (unsigned char)ch;

	if( g_dosCodePage == 866u )
	{
		if( ch >= 0x410ul && ch <= 0x43Ful )
			return (unsigned char)(128u + ch - 0x410ul);
		if( ch >= 0x440ul && ch <= 0x44Ful )
			return (unsigned char)(224u + ch - 0x440ul);
		if( ch == 0x401ul )
			return 240;
		if( ch == 0x451ul )
			return 241;
	}

	const unsigned short *table = g_cp437_to_unicode;
	switch( g_dosCodePage )
	{
	case 850: table = g_cp850_to_unicode; break;
	case 852: table = g_cp852_to_unicode; break;
	case 866: table = g_cp866_to_unicode; break;
	}

	for( int i = 0; i < 128; i++ )
		if( table[i] == ch )
			return (unsigned char)(i + 128u);
	return '?';
}

size_t DosOemToUtf8(unsigned char ch, unsigned char out[4])
{
	int u = DosOemUnicode(ch);
	if( u < 0x80 )
	{
		out[0] = (unsigned char)u;
		return 1;
	}
	if( u < 0x800 )
	{
		out[0] = (unsigned char)(0xC0 | (u >> 6));
		out[1] = (unsigned char)(0x80 | (u & 63u));
		return 2;
	}
	out[0] = (unsigned char)(0xE0 | (u >> 12));
	out[1] = (unsigned char)(0x80 | ((u >> 6) & 63u));
	out[2] = (unsigned char)(0x80 | (u & 63u));
	return 3;
}

bool DosOemString(const char *src, char *dst, size_t capacity)
{
	size_t used = 0;
	while( *src )
	{
		unsigned char utf[4];
		size_t n = DosOemToUtf8((unsigned char)*src++, utf);
		if( used + n >= capacity )
			return false;

		memcpy(dst + used, utf, n);
		used += n;
	}
	dst[used] = '\0';
	return used != 0;
}

