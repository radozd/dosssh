static int g_dosCodePage = 866;

void InitDosCharset()
{
	union REGS r;
	r.x.ax = 0x6601;
	intdos(&r, &r);
	switch( r.x.bx )
	{
	case 852:
		g_dosCodePage = 852;
		break;

	case 850:
	case 858:
		g_dosCodePage = 850;
		break;

	case 437:
		g_dosCodePage = 437;
		break;

	default:
		g_dosCodePage = 866;
	}
	printf("DOS CP%d\n", r.x.bx);
}

