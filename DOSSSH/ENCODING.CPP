void DosUtf8Decoder::Reset()
{
	_value = 0;
	_min = 0;
	_need = 0;
}

bool DosUtf8Decoder::Start(unsigned char ch)
{
	if( ch >= 0xC2 && ch <= 0xDF )
	{
		_value = ch & 31u;
		_min = 0x80u;
		_need = 1;
	}
	else if( ch >= 0xE0 && ch <= 0xEF )
	{
		_value = ch & 15u;
		_min = 0x800u;
		_need = 2;
	}
	else if( ch >= 0xF0 && ch <= 0xF4 )
	{
		_value = ch & 7u;
		_min = 0x10000ul;
		_need = 3;
	}
	else
		return false;
	return true;
}

long DosUtf8Decoder::Continue(unsigned char ch)
{
	if( (ch & 0xC0) != 0x80 )
	{
		_need = 0;
		return Interrupted;
	}

	_value = (_value << 6) | (ch & 63u);
	if( --_need != 0 )
		return PendingByte;

	if( _value < _min || _value > 0x10FFFFul || (_value >= 0xD800 && _value <= 0xDFFF) )
		return Invalid;
	return (long)_value;
}
